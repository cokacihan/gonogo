"""Record a real MCP session with `gonogo.mcp_server` over stdio, as an agent would run it, into docs/MCP_SESSION.md.

A scripted client starts the server as a subprocess, does the MCP handshake, lists the tools and makes the calls a
coding agent makes before and after an edit. The requests and responses are the bytes on the wire (long responses are
shortened, and the shortening is marked). No language model is in this loop: it shows exactly what an agent receives.

  python -m eval.mcp_session   -> docs/MCP_SESSION.md
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "MCP_SESSION.md"

CALLS = [
    ("Before editing a library header: which unit tests must I re-run?",
     "tests_to_rerun", {"files": ["Utils/Types/CircularBuffer.hpp"]}),
    ("Why is this requirement not GO?", "why", {"id": "HTH-001"}),
    ("Where would the missing citation go?", "suggest", {"id": "TLC-006", "k": 3}),
    ("A question in words, answered with its Cypher receipt", "ask",
     {"question": "Which requirements of Svc/TlmChan are not verified?"}),
]


def shorten(value, depth=0):
    """Keep the shape of a response readable: long lists are cut, and the cut says how much was left out."""
    if isinstance(value, list):
        items = [shorten(v, depth + 1) for v in value[:3]]
        return items + ([f"... {len(value) - 3} more"] if len(value) > 3 else [])
    if isinstance(value, dict):
        return {k: shorten(v, depth + 1) for k, v in value.items()}
    if isinstance(value, str) and len(value) > 400:
        return value[:400] + f"... ({len(value) - 400} more characters)"
    return value


def main() -> None:
    proc = subprocess.Popen([sys.executable, "-m", "gonogo.mcp_server"], cwd=ROOT, stdin=subprocess.PIPE,
                            stdout=subprocess.PIPE, text=True, encoding="utf-8")
    log = []

    def send(msg, reply=True):
        proc.stdin.write(json.dumps(msg) + "\n")
        proc.stdin.flush()
        return json.loads(proc.stdout.readline()) if reply else None

    init = send({"jsonrpc": "2.0", "id": 1, "method": "initialize", "params": {
        "protocolVersion": "2025-06-18", "capabilities": {}, "clientInfo": {"name": "scripted-client", "version": "1"}}})
    send({"jsonrpc": "2.0", "method": "notifications/initialized"}, reply=False)
    tools = send({"jsonrpc": "2.0", "id": 2, "method": "tools/list"})["result"]["tools"]
    for i, (why, name, args) in enumerate(CALLS, 3):
        req = {"jsonrpc": "2.0", "id": i, "method": "tools/call", "params": {"name": name, "arguments": args}}
        resp = send(req)
        body = json.loads(resp["result"]["content"][0]["text"])
        log.append((why, req, body, resp["result"].get("isError", False)))
    proc.stdin.close()
    proc.wait(timeout=60)

    lines = ["# An MCP session with the GoNoGo server (generated by `python -m eval.mcp_session`)", "",
             "A scripted MCP client started `python -m gonogo.mcp_server` over stdio and made the calls below. The "
             "requests and responses are what went over the wire; long lists and strings are shortened, and each cut "
             "says how much was left out. No language model is in this loop: this is exactly what an agent such as "
             "Claude Desktop or Claude Code receives when [`.mcp.json.example`](../.mcp.json.example) is configured.", "",
             f"Server: `{init['result']['serverInfo']['name']}` {init['result']['serverInfo']['version']}, protocol "
             f"`{init['result']['protocolVersion']}`. Tools (all read-only):", ""]
    lines += [f"- `{t['name']}`: {t['description']}" for t in tools]
    for why, req, body, is_error in log:
        lines += ["", f"## {why}", "", "Request:", "", "```json", json.dumps(req, ensure_ascii=False), "```", "",
                  f"Response{' (error)' if is_error else ''}:", "", "```json",
                  json.dumps(shorten(body), indent=1, ensure_ascii=False), "```"]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(log)} calls, exit {proc.returncode}")


if __name__ == "__main__":
    main()
