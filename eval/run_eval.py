"""Benchmark: graph agent vs. vector-only retrieval vs. full-text retrieval, on the synthetic set.

All three systems query the SAME Relate store. Expected answers come from ground_truth.json,
which is computed in plain Python (gonogo/truth.py), not through Relate.

Usage:  python -m eval.run_eval            (writes eval/results.json and eval/RESULTS.md)
"""
from __future__ import annotations

import json
import re
import statistics
import time
from pathlib import Path

from eval.questions import question_sets
from gonogo.agent import Agent
from gonogo.db import DATA_DIR, DB_PATH, connect
from gonogo.queries import run

K = 10  # retrieval depth for the baselines
OUT = Path(__file__).resolve().parent


def agent_system(agent: Agent):
    def answer(q: dict) -> set[str]:
        a = agent.ask(q["text"])
        return set(a.answer_ids) if a.status == "answered" else set()
    return answer


def vector_system(db):
    def answer(q: dict) -> set[str]:
        rows, _, _ = run(db, "vector_search", q=q["text"], k=K)
        return {r["id"] for r in rows if r["label"] in q["labels"]} if q["labels"] else {r["id"] for r in rows}
    return answer


def fulltext_system(db):
    def answer(q: dict) -> set[str]:
        words = re.findall(r"[A-Za-z0-9]+(?:-[A-Za-z0-9]+)*", q["text"])
        query = " OR ".join(f'"{w}"' if "-" in w else w for w in words)
        rows, _, _ = run(db, "fulltext_search", text=query, k=K)
        return {r["id"] for r in rows if r["label"] in q["labels"]} if q["labels"] else {r["id"] for r in rows}
    return answer


def score(expected: set[str], got: set[str], answerable: bool) -> dict:
    if not answerable:
        ok = float(len(got) == 0)
        return {"precision": ok, "recall": ok, "f1": ok, "exact": ok}
    tp = len(expected & got)
    p = tp / len(got) if got else 0.0
    r = tp / len(expected) if expected else float(not got)
    f1 = 2 * p * r / (p + r) if p + r else 0.0
    return {"precision": p, "recall": r, "f1": f1, "exact": float(expected == got)}


def evaluate(systems: dict, questions: list[dict]) -> tuple[dict, list[dict]]:
    per_q, summary = [], {}
    for name, fn in systems.items():
        rows = []
        for q in questions:
            t0 = time.perf_counter()
            got = fn(q)
            ms = (time.perf_counter() - t0) * 1e3
            s = score(set(q["expected"]), got, q["answerable"])
            rows.append({"system": name, "qid": q["qid"], "text": q["text"], "category": q["category"],
                         "answerable": q["answerable"], "got": sorted(got), "ms": round(ms, 2),
                         **{k: round(v, 4) for k, v in s.items()}})
        per_q += rows
        ans = [r for r in rows if r["answerable"]]
        oos = [r for r in rows if not r["answerable"]]
        summary[name] = {
            "questions": len(rows),
            "answerable_macro_f1": round(statistics.mean(r["f1"] for r in ans), 3),
            "answerable_exact_match": round(statistics.mean(r["exact"] for r in ans), 3),
            "answerable_macro_precision": round(statistics.mean(r["precision"] for r in ans), 3),
            "answerable_macro_recall": round(statistics.mean(r["recall"] for r in ans), 3),
            "out_of_scope_abstention": round(statistics.mean(r["exact"] for r in oos), 3),
            "median_ms": round(statistics.median(r["ms"] for r in rows), 2),
            "by_category_f1": {c: round(statistics.mean(r["f1"] for r in rows if r["category"] == c), 3)
                               for c in sorted({r["category"] for r in rows})},
        }
    return summary, per_q


def main() -> dict:
    gt = json.loads((DATA_DIR / "ground_truth.json").read_text(encoding="utf-8"))
    sets = question_sets(gt)
    (OUT / "questions.json").write_text(json.dumps(sets["original"], indent=1), encoding="utf-8")
    db = connect(DB_PATH)
    systems = {"graph_agent": agent_system(Agent(db)), "vector_only": vector_system(db),
               "fulltext_only": fulltext_system(db)}
    result = {"dataset_seed": gt["seed"], "k": K, "sets": {}}
    for set_name, qs in sets.items():
        summary, per_q = evaluate(systems, qs)
        result["sets"][set_name] = {"n_questions": len(qs), "summary": summary, "per_question": per_q}
    db.close()
    (OUT / "results.json").write_text(json.dumps(result, indent=1), encoding="utf-8")
    (OUT / "RESULTS.md").write_text(render_md(result), encoding="utf-8")
    return result


def render_md(res: dict) -> str:
    lines = ["# Benchmark results (generated by `python -m eval.run_eval` — do not edit by hand)", "",
             f"Synthetic KESTREL-3U dataset, seed {res['dataset_seed']}; retrieval depth k={res['k']} for the baselines.",
             "All systems query the same Relate store; expected answers come from `data/ground_truth.json`,",
             "computed in plain Python without Relate.", ""]
    labels = [("answerable_macro_f1", "Answerable: macro F1"), ("answerable_exact_match", "Answerable: exact set match"),
              ("out_of_scope_abstention", "Out-of-scope: correct abstention"), ("median_ms", "Median latency (ms)")]
    for set_name, block in res["sets"].items():
        s = block["summary"]
        names = list(s)
        lines += [f"## Question set: `{set_name}` ({block['n_questions']} questions)", "",
                  "| Metric | " + " | ".join(names) + " |", "|---|" + "---|" * len(names)]
        lines += [f"| {lab} | " + " | ".join(str(s[n][key]) for n in names) + " |" for key, lab in labels]
        cats = sorted(next(iter(s.values()))["by_category_f1"])
        lines += ["", "<details><summary>F1 by category</summary>", "",
                  "| Category | " + " | ".join(names) + " |", "|---|" + "---|" * len(names)]
        lines += [f"| {c} | " + " | ".join(str(s[n]["by_category_f1"][c]) for n in names) + " |" for c in cats]
        lines += ["", "</details>", ""]
    lines += ["## How to read this", "",
              "- `original`: questions and agent keyword rules were written by the same author, so the agent score",
              "  there is an upper bound.",
              "- `paraphrase_dev` / `paraphrase_heldout`: rewordings generated by an external LLM that never saw the",
              "  rules (see `eval/paraphrases.json` for provenance). Rules may be improved on `dev`; `heldout` is the",
              "  honest generalisation estimate.",
              "- Baselines are told the answer node type and return their top-k matches.",
              "- The embedding is a lexical hashed trigram vector, not a neural model."]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    r = main()
    for name, block in r["sets"].items():
        print(name, {k: (v["answerable_macro_f1"], v["out_of_scope_abstention"]) for k, v in block["summary"].items()})
