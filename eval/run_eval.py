"""Benchmark: graph agent vs. vector-only retrieval vs. full-text retrieval, on the synthetic set.

All three systems query the SAME Relate store. Expected answers come from ground_truth.json,
which is computed in plain Python (tracegraph/truth.py), not through Relate.

Usage:  python -m eval.run_eval            (writes eval/results.json and eval/RESULTS.md)
"""
from __future__ import annotations

import json
import re
import statistics
import time
from pathlib import Path

from eval.questions import build_questions
from tracegraph.agent import Agent
from tracegraph.db import DATA_DIR, DB_PATH, connect
from tracegraph.queries import run

K = 10  # retrieval depth for the baselines
OUT = Path(__file__).resolve().parent


def agent_system(agent: Agent):
    def answer(q: dict) -> set[str]:
        a = agent.ask(q["text"])
        return set(a.answer_ids) if a.status == "answered" else set()
    return answer


def vector_system(db):
    def answer(q: dict) -> set[str]:
        rows, _, _ = run(db, "vector_search", q=q["text"], k=K)
        return {r["id"] for r in rows if r["label"] in q["labels"]} if q["labels"] else {r["id"] for r in rows}
    return answer


def fulltext_system(db):
    def answer(q: dict) -> set[str]:
        words = re.findall(r"[A-Za-z0-9]+(?:-[A-Za-z0-9]+)*", q["text"])
        query = " OR ".join(f'"{w}"' if "-" in w else w for w in words)
        rows, _, _ = run(db, "fulltext_search", text=query, k=K)
        return {r["id"] for r in rows if r["label"] in q["labels"]} if q["labels"] else {r["id"] for r in rows}
    return answer


def score(expected: set[str], got: set[str], answerable: bool) -> dict:
    if not answerable:
        ok = float(len(got) == 0)
        return {"precision": ok, "recall": ok, "f1": ok, "exact": ok}
    tp = len(expected & got)
    p = tp / len(got) if got else 0.0
    r = tp / len(expected) if expected else float(not got)
    f1 = 2 * p * r / (p + r) if p + r else 0.0
    return {"precision": p, "recall": r, "f1": f1, "exact": float(expected == got)}


def main() -> dict:
    gt = json.loads((DATA_DIR / "ground_truth.json").read_text(encoding="utf-8"))
    questions = build_questions(gt)
    (OUT / "questions.json").write_text(json.dumps(questions, indent=1), encoding="utf-8")
    db = connect(DB_PATH)
    systems = {"graph_agent": agent_system(Agent(db)), "vector_only": vector_system(db),
               "fulltext_only": fulltext_system(db)}
    per_q, summary = [], {}
    for name, fn in systems.items():
        rows = []
        for q in questions:
            t0 = time.perf_counter()
            got = fn(q)
            ms = (time.perf_counter() - t0) * 1e3
            s = score(set(q["expected"]), got, q["answerable"])
            rows.append({"system": name, "qid": q["qid"], "category": q["category"], "answerable": q["answerable"],
                         "got": sorted(got), "ms": round(ms, 2), **{k: round(v, 4) for k, v in s.items()}})
        per_q += rows
        ans = [r for r in rows if r["answerable"]]
        oos = [r for r in rows if not r["answerable"]]
        summary[name] = {
            "questions": len(rows),
            "answerable_macro_f1": round(statistics.mean(r["f1"] for r in ans), 3),
            "answerable_exact_match": round(statistics.mean(r["exact"] for r in ans), 3),
            "answerable_macro_precision": round(statistics.mean(r["precision"] for r in ans), 3),
            "answerable_macro_recall": round(statistics.mean(r["recall"] for r in ans), 3),
            "out_of_scope_abstention": round(statistics.mean(r["exact"] for r in oos), 3),
            "median_ms": round(statistics.median(r["ms"] for r in rows), 2),
            "by_category_f1": {c: round(statistics.mean(r["f1"] for r in rows if r["category"] == c), 3)
                               for c in sorted({r["category"] for r in rows})},
        }
    db.close()
    result = {"dataset_seed": gt["seed"], "k": K, "n_questions": len(questions), "summary": summary, "per_question": per_q}
    (OUT / "results.json").write_text(json.dumps(result, indent=1), encoding="utf-8")
    (OUT / "RESULTS.md").write_text(render_md(result), encoding="utf-8")
    return result


def render_md(res: dict) -> str:
    s = res["summary"]
    names = list(s)
    lines = [
        "# Benchmark results (generated by `python -m eval.run_eval` — do not edit by hand)", "",
        f"Synthetic KESTREL-3U dataset, seed {res['dataset_seed']}, {res['n_questions']} questions, "
        f"retrieval depth k={res['k']} for the baselines.", "",
        "| Metric | " + " | ".join(names) + " |", "|---|" + "---|" * len(names),
    ]
    for key, label in [("answerable_macro_f1", "Answerable: macro F1"), ("answerable_exact_match", "Answerable: exact set match"),
                       ("answerable_macro_precision", "Answerable: macro precision"), ("answerable_macro_recall", "Answerable: macro recall"),
                       ("out_of_scope_abstention", "Out-of-scope: correct abstention"), ("median_ms", "Median latency (ms)")]:
        lines.append(f"| {label} | " + " | ".join(str(s[n][key]) for n in names) + " |")
    cats = sorted(next(iter(s.values()))["by_category_f1"])
    lines += ["", "F1 by category:", "", "| Category | " + " | ".join(names) + " |", "|---|" + "---|" * len(names)]
    lines += [f"| {c} | " + " | ".join(str(s[n]["by_category_f1"][c]) for n in names) + " |" for c in cats]
    lines += ["", "Limitations: the questions and the agent's keyword rules were written by the same author, so the",
              "graph agent's score is an upper bound for this question set. Baselines are told the answer node type.",
              "The embedding is a lexical hashed trigram vector, not a neural model."]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    r = main()
    print(json.dumps(r["summary"], indent=1))
