"""Bundle the graph and the exact Cypher used by the CLI for the browser explorer (Relate WASM).

    python -m gonogo.web_export [--out web/data]

Writes:
  graph.json     nodes grouped by label and relationships grouped by type (no embeddings), including the CI run
  queries.json   the verdict, impact and integration Cypher strings from gonogo/verdict.py and gonogo/impact.py,
                 plus the read-only templates, so the browser runs the very same queries as `python -m gonogo`
  stats.json     docs/stats.json (headline numbers, release timeline, mutation summary), generated by gonogo.stats
The browser cannot open a Relate directory or .rl file, so it loads graph.json into an in-memory database
with UNWIND batches.
"""
from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path

from gonogo import db as store
from gonogo.impact import INTEGRATION_CYPHER, TESTS_TO_RERUN_CYPHER
from gonogo.queries import T
from gonogo.verdict import DRIFT_PATH_CYPHER, EVIDENCE_PATHS_CYPHER, TEST_METHODS, VERDICTS_CYPHER

ROOT = Path(__file__).resolve().parents[1]
DROP = {"embedding", "calls"}
KEEP_TEXT = {"Requirement", "TestRun"}


def bundle(dataset: dict, results: dict | None) -> dict:
    nodes = {label: [{k: v for k, v in n.items() if k not in DROP and (k != "text" or label in KEEP_TEXT)}
                     for n in rows] for label, rows in dataset["nodes"].items()}
    edges = list(dataset["edges"])
    case_ids = {c["id"] for c in dataset["nodes"].get("TestCase", [])}
    run, run_edges, unmapped = store.results_edges(results, case_ids)
    if run:
        nodes["TestRun"] = [run]
        edges += [{k: v for k, v in e.items() if k != "reported_as"} for e in run_edges]
    by_type = defaultdict(list)
    for e in edges:
        by_type[e["type"]].append({k: v for k, v in e.items() if k != "type"})
    return {"meta": {"source": dataset["source"], "run": run, "results_unmapped": len(unmapped)},
            "nodes": nodes, "edges": dict(by_type)}


def queries() -> dict:
    from gonogo.cli import REASON_TEXT
    return {"reason_text": REASON_TEXT, "verdicts": VERDICTS_CYPHER.strip(), "tests_to_rerun": TESTS_TO_RERUN_CYPHER.strip(),
            "integration": INTEGRATION_CYPHER.strip(),
            "evidence_paths": EVIDENCE_PATHS_CYPHER.strip(), "drift_path": DRIFT_PATH_CYPHER.strip(), "test_methods": sorted(TEST_METHODS),
            "templates": {name: {"title": t.title, "cypher": t.cypher, "params": list(t.params)}
                          for name, t in T.items() if not name.startswith("vector")}}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "web" / "data"))
    a = ap.parse_args(argv)
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    ds, res = store.load_inputs()
    b = bundle(ds, res)
    (out / "graph.json").write_text(json.dumps(b, separators=(",", ":")), encoding="utf-8")
    (out / "queries.json").write_text(json.dumps(queries(), indent=1), encoding="utf-8")
    stats = ROOT / "docs" / "stats.json"
    if stats.exists():
        (out / "stats.json").write_text(stats.read_text(encoding="utf-8"), encoding="utf-8")
    n = sum(len(v) for v in b["nodes"].values())
    m = sum(len(v) for v in b["edges"].values())
    print(f"wrote {out}: {n} nodes, {m} relationships, graph.json {(out / 'graph.json').stat().st_size / 1e6:.2f} MB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
